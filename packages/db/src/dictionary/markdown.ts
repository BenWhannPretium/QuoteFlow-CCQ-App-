import type { DictionaryTable } from './model';
import { AREA_ORDER } from './model';

const AREA_TITLE: Record<string, string> = {
  identity: 'Identity and access (`schema/identity.ts`)',
  config: 'Reference and config (`schema/config.ts`)',
  workflow: 'Core workflow (`schema/workflow.ts`)',
  events: 'Events and audit (`schema/events.ts`)',
  integration: 'Integration (`schema/integration.ts`)',
};

const cell = (text: string | null) => (text ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** Render the data dictionary. Deterministic (no timestamps) so CI can diff it. */
export function renderMarkdown(tables: DictionaryTable[]): string {
  const out: string[] = [
    '# QuoteFlow data dictionary',
    '',
    '> Generated by `pnpm db:dictionary` from the Drizzle schema comments in `packages/db/src/schema/`. **Do not edit by hand.**',
    '> The same text is applied to the database as `COMMENT ON` after every migration. Starting point for the M6 review with D&A.',
    '',
    'Conventions: every table has `id` (UUID v7, generated in app code), `created_at`, `updated_at` and `created_by`.',
    'Config tables also carry `version`, `provisional`, `approved_by` and `approved_at`. Times are UTC `timestamptz`.',
    'Columns marked *Commercial* are stripped server-side for roles without `quote.read.commercialFields`.',
    '',
    '## Tables',
    '',
  ];
  for (const area of AREA_ORDER) {
    const inArea = tables.filter((t) => t.area === area);
    if (inArea.length === 0) continue;
    out.push(
      `- **${AREA_TITLE[area]}:** ${inArea.map((t) => `[\`${t.name}\`](#${t.name})`).join(', ')}`,
    );
  }
  for (const area of AREA_ORDER) {
    const inArea = tables.filter((t) => t.area === area);
    if (inArea.length === 0) continue;
    out.push('', `## ${AREA_TITLE[area]}`);
    for (const t of inArea) {
      out.push('', `### ${t.name}`, '', `${t.description}`, '', `**Owner:** ${t.owner}`, '');
      out.push(
        '| Column | Type | Null | Default | References | Meaning | Owner |',
        '|---|---|---|---|---|---|---|',
      );
      for (const col of t.columns) {
        out.push(
          `| \`${col.name}\` | ${cell(col.sqlType)} | ${col.nullable ? 'yes' : 'no'} | ${cell(col.default)} | ${cell(col.references)} | ${cell(col.meaning)} | ${cell(col.owner)} |`,
        );
      }
      if (t.checks.length > 0)
        out.push('', `**Checks:** ${t.checks.map((ch) => `\`${ch.name}\``).join(', ')}`);
      if (t.indexes.length > 0)
        out.push('', `**Indexes:** ${t.indexes.map((ix) => `\`${ix}\``).join(', ')}`);
    }
  }
  out.push('');
  return out.join('\n');
}
